"""Local BIT change-detection runtime boundary.

The real Open-CD/BIT wrapper will live here and return structured spatial
evidence, never a natural-language answer.
"""

from __future__ import annotations

import os
import sys
import threading
import json
from pathlib import Path
from typing import Any

from backend.config import settings


class BITRuntime:
    """Local BIT-CD runtime following the validated ``BIT.ipynb`` wrapper.

    It deliberately consumes the paired 256px RGB PNG tiles generated by the
    bi-temporal preprocessor.  This matches the notebook's
    ``CDDataAugmentation -> CDEvaluator._forward_pass -> G_pred`` flow.
    """

    def __init__(self, checkpoint_path: str | None = None) -> None:
        self.checkpoint_path = checkpoint_path or settings.BIT_CHECKPOINT_PATH
        self.root = Path(settings.BIT_ROOT) if settings.BIT_ROOT else None
        self.device: Any = None
        self.model: Any = None
        self._load_lock = threading.Lock()

    def is_available(self) -> bool:
        if not self.root:
            return False
        if self.checkpoint_path:
            return Path(self.checkpoint_path).exists()
        return (self.root / "checkpoints" / settings.BIT_PROJECT_NAME / settings.BIT_CHECKPOINT_NAME).exists()

    def _load_model(self) -> None:
        if self.model is not None:
            return
        with self._load_lock:
            if self.model is not None:
                return
            if not self.root or not self.root.exists():
                raise RuntimeError("BIT_ROOT must point to the validated local BIT_CD repository.")
            if str(self.root) not in sys.path:
                sys.path.insert(0, str(self.root))
            try:
                import torch
                from datasets.CD_dataset import CDDataAugmentation
                from models.basic_model import CDEvaluator
            except ImportError as exc:
                raise RuntimeError(
                    "BIT dependencies are unavailable. Use the isolated Open-CD/BIT environment "
                    "recorded in models/BIT.ipynb."
                ) from exc

            class Args:
                pass

            args = Args()
            args.gpu_ids = [0] if torch.cuda.is_available() else []
            args.checkpoint_root = str(self.root / "checkpoints")
            args.project_name = settings.BIT_PROJECT_NAME
            args.checkpoint_dir = os.path.join(args.checkpoint_root, args.project_name)
            args.output_folder = str(self.root / "samples" / "satquery_output")
            Path(args.output_folder).mkdir(parents=True, exist_ok=True)
            args.net_G = "base_transformer_pos_s4_dd8_dedim8"
            args.n_class = 2
            args.embed_dim = 256
            args.img_size = settings.BIT_IMAGE_SIZE

            checkpoint_name = settings.BIT_CHECKPOINT_NAME
            if self.checkpoint_path:
                checkpoint = Path(self.checkpoint_path)
                args.checkpoint_root = str(checkpoint.parent.parent)
                args.project_name = checkpoint.parent.name
                args.checkpoint_dir = str(checkpoint.parent)
                checkpoint_name = checkpoint.name

            model = CDEvaluator(args)
            model.load_checkpoint(checkpoint_name)
            model.eval()
            self.device = torch.device("cuda:0" if torch.cuda.is_available() else "cpu")
            self.model = model
            self._augmentation_type = CDDataAugmentation

    def _preprocess(self, image_path: str) -> tuple[Any, tuple[int, int]]:
        """Exact model input preparation used by the notebook's SatQueryBIT."""
        from PIL import Image
        image = Image.open(image_path).convert("RGB")
        original_size = image.size
        import numpy as np
        image_array = np.asarray(image)
        augmentation = self._augmentation_type(img_size=settings.BIT_IMAGE_SIZE)
        [tensor], _ = augmentation.transform([image_array], [], to_tensor=True)
        return tensor.unsqueeze(0), original_size

    @staticmethod
    def _prediction_to_mask(prediction: Any) -> Any:
        import numpy as np
        array = prediction.detach().cpu().numpy()
        if array.ndim == 4:
            array = array[0]
            array = np.argmax(array, axis=0) if array.shape[0] == 2 else array[0]
        elif array.ndim == 3:
            array = array[0]
        return (array > 0).astype(np.uint8)

    def _artifact_dirs(self, before_path: str) -> dict[str, Path]:
        path = Path(before_path).resolve()
        # Expected paired-tile layout: data/jobs/<job>/tiles/t1/<tile>.png.
        job_dir = path.parent.parent.parent if path.parent.name in {"t1", "t2"} else path.parent
        dirs = {name: job_dir / name for name in ("masks", "regions", "overlays")}
        for directory in dirs.values():
            directory.mkdir(parents=True, exist_ok=True)
        return dirs

    @staticmethod
    def _region_geometry(region: dict[str, Any], metadata: dict[str, Any]) -> None:
        """Attach local, global-pixel, native-CRS and WGS84 bounds when available."""
        x1, y1, x2, y2 = region["bbox"]
        region["local_bbox"] = [x1, y1, x2, y2]
        col_off, row_off = int(metadata.get("col_off", 0)), int(metadata.get("row_off", 0))
        region["global_pixel_bbox"] = [col_off + x1, row_off + y1, col_off + x2, row_off + y2]
        region["tile_id"] = metadata.get("tile_id")
        region["crs"] = metadata.get("crs")
        transform = metadata.get("transform") or []
        if len(transform) >= 6:
            a, b, c, d, e, f = (float(value) for value in transform[:6])
            corners = [(a * x + b * y + c, d * x + e * y + f) for x, y in ((x1, y1), (x2, y1), (x2, y2), (x1, y2))]
            region["native_crs_polygon"] = [[round(px, 8), round(py, 8)] for px, py in corners]
            region["native_crs_bbox"] = [min(p[0] for p in corners), min(p[1] for p in corners), max(p[0] for p in corners), max(p[1] for p in corners)]
        bounds = metadata.get("bounds_wgs84")
        width, height = int(metadata.get("width", 0)), int(metadata.get("height", 0))
        if bounds and len(bounds) == 4 and width and height:
            min_lon, min_lat, max_lon, max_lat = (float(value) for value in bounds)
            def to_wgs(x: int, y: int) -> list[float]:
                return [round(min_lon + x / width * (max_lon - min_lon), 8), round(max_lat - y / height * (max_lat - min_lat), 8)]
            corners = [to_wgs(x, y) for x, y in ((x1, y1), (x2, y1), (x2, y2), (x1, y2))]
            region["wgs84_polygon"] = corners
            region["bbox_wgs84"] = [min(p[0] for p in corners), min(p[1] for p in corners), max(p[0] for p in corners), max(p[1] for p in corners)]

    def analyze(self, before_path: str, after_path: str, *, artifact_prefix: str = "bit", tile_metadata: dict[str, Any] | None = None) -> dict[str, Any]:
        if not self.is_available():
            raise RuntimeError(
                "BIT is not configured. Set BIT_ROOT or BIT_CHECKPOINT_PATH to the validated "
                "local BIT-CD checkpoint before enabling temporal inference."
            )
        self._load_model()
        import cv2
        import numpy as np
        import torch
        from PIL import Image

        before, before_size = self._preprocess(before_path)
        after, after_size = self._preprocess(after_path)
        batch = {"A": before.to(self.device), "B": after.to(self.device)}
        with torch.no_grad():
            self.model._forward_pass(batch)
            mask = self._prediction_to_mask(self.model.G_pred)

        # Exact post-processing from the final BIT notebook cell: connect
        # nearby change pixels, remove isolated noise, then extract regions.
        raw_mask = mask
        mask_uint8 = raw_mask * 255
        close_kernel = np.ones((settings.BIT_CLOSE_KERNEL_SIZE, settings.BIT_CLOSE_KERNEL_SIZE), np.uint8)
        open_kernel = np.ones((settings.BIT_OPEN_KERNEL_SIZE, settings.BIT_OPEN_KERNEL_SIZE), np.uint8)
        clean_mask = cv2.morphologyEx(mask_uint8, cv2.MORPH_CLOSE, close_kernel)
        clean_mask = cv2.morphologyEx(clean_mask, cv2.MORPH_OPEN, open_kernel)
        mask = (clean_mask > 0).astype(np.uint8)

        changed_pixels = int(mask.sum())
        total_pixels = int(mask.size)
        count, _, stats, _ = cv2.connectedComponentsWithStats(mask, connectivity=8)
        regions: list[dict[str, Any]] = []
        for label in range(1, count):
            x, y, width, height, area = (int(value) for value in stats[label])
            if area >= settings.BIT_MIN_REGION_AREA:
                regions.append({
                    "id": len(regions) + 1, "bbox": [x, y, x + width, y + height],
                    "x": x, "y": y, "width": width, "height": height, "area": area,
                })
        regions.sort(key=lambda region: region["area"], reverse=True)

        artifact_dirs = self._artifact_dirs(before_path)
        raw_mask_path = artifact_dirs["masks"] / f"{artifact_prefix}_raw_change_mask.png"
        Image.fromarray((raw_mask * 255).astype(np.uint8)).save(raw_mask_path)
        mask_path = artifact_dirs["masks"] / f"{artifact_prefix}_change_mask.png"
        Image.fromarray((mask * 255).astype(np.uint8)).save(mask_path)
        after_image = np.asarray(Image.open(after_path).convert("RGB"))
        resized_mask = cv2.resize(mask, (after_image.shape[1], after_image.shape[0]), interpolation=cv2.INTER_NEAREST)
        overlay = after_image.copy()
        overlay[resized_mask > 0] = [255, 0, 0]
        overlay_path = artifact_dirs["overlays"] / f"{artifact_prefix}_change_overlay.png"
        Image.fromarray(cv2.addWeighted(after_image, 0.55, overlay, 0.45, 0)).save(overlay_path)
        crop_paths: list[str] = []
        for region in regions:
            x1, y1, x2, y2 = region["bbox"]
            self._region_geometry(region, tile_metadata or {})
            region["before_tile_path"] = before_path
            region["after_tile_path"] = after_path
            crop = after_image[y1:y2, x1:x2]
            if crop.size == 0:
                continue
            crop_path = artifact_dirs["regions"] / f"{artifact_prefix}_region_{region['id']:03d}.png"
            Image.fromarray(crop).save(crop_path)
            region["crop_path"] = str(crop_path)
            crop_paths.append(str(crop_path))

        regions_path = artifact_dirs["regions"] / f"{artifact_prefix}_regions.json"
        regions_path.write_text(json.dumps(regions, indent=2), encoding="utf-8")

        return {
            "model": "BIT", "before_size": list(before_size), "after_size": list(after_size),
            "raw_mask_path": str(raw_mask_path), "mask_path": str(mask_path), "overlay_path": str(overlay_path),
            "changed_pixel_count": changed_pixels, "total_pixels": total_pixels,
            "change_percentage": round((changed_pixels / total_pixels * 100) if total_pixels else 0.0, 4),
            "regions": regions, "num_regions": len(regions),
            "region_crops": crop_paths,
            "regions_path": str(regions_path),
            "artifact_paths": [str(raw_mask_path), str(mask_path), str(overlay_path), str(regions_path), *crop_paths],
        }


_runtime: BITRuntime | None = None


def get_bit_runtime() -> BITRuntime:
    global _runtime
    if _runtime is None:
        _runtime = BITRuntime()
    return _runtime
