def test_14_and_15_reservoir_water_genuine_mask_validation():
    """14 & 15. Water highlight produces genuine pixel-level spatial mask."""
    h, w = 100, 100
    valid_water = np.zeros((h, w), dtype=bool)
    valid_water[30:70, 20:60] = True  # genuine reservoir shape

    is_valid, err = validate_mask_array(valid_water)
    assert is_valid is True
    assert err is None

    # Reject empty mask (< 4 pixels)
    empty_mask = np.zeros((h, w), dtype=bool)
    is_valid_empty, err_empty = validate_mask_array(empty_mask)
    assert is_valid_empty is False

    # Reject full-scene fake bounding box mask (100% full rectangle)
    fake_full = np.ones((h, w), dtype=bool)
    is_valid_fake, err_fake = validate_mask_array(fake_full, allow_full_scene=False)
    assert is_valid_fake is False


